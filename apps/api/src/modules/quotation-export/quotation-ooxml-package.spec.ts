import ExcelJS from 'exceljs';
import JSZip from 'jszip';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  captureTemplateDrawings,
  type TemplateDrawingSnapshot,
} from './quotation-drawing-preserver';
import { fitImageIntoCell, measureQuotationImageCell, pixelsToEmu } from './quotation-image-fitter';
import type { QuotationProductImageAnchor } from './quotation-image-embedder';
import {
  ensureQuotationOoxmlImages,
  validateQuotationOoxmlImages,
  type OoxmlExpectedProductImage,
  type QuotationOoxmlValidationOptions,
} from './quotation-ooxml-package';
import { buildQuotationWorkbookFromTemplate } from './quotation-template-workbook';
import type { QuotationWorkbookProduct } from './quotation-workbook';

const TEMPLATE = readFileSync(
  resolve(process.cwd(), '../../assets/templates/B2B_Quotation_Template.xlsx'),
);
const PNG = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9Zt9sAAAAASUVORK5CYII=',
  'base64',
);
const FIELD_MAPPING = {
  A: 'product.sku',
  B: 'product.image',
  C: 'product.name',
  D: 'product.price_cny',
  E: 'product.carton_qty',
  F: 'product.carton_size_cm',
  G: 'product.carton_weight_kg',
} as const;

function product(productId: string, width: number, height: number): QuotationWorkbookProduct {
  return {
    productId,
    sku: productId.toUpperCase(),
    englishName: productId,
    unitPrice: '10.00',
    cartonQuantity: 12,
    cartonDimensions: '40 × 30 × 30 cm',
    cartonGrossWeightKg: '12.500',
    image: { buffer: PNG, extension: 'png', width, height },
  };
}

async function expectedPackage(): Promise<{
  options: QuotationOoxmlValidationOptions;
  snapshot: TemplateDrawingSnapshot;
}> {
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(TEMPLATE as unknown as Parameters<typeof workbook.xlsx.load>[0]);
  const worksheet = workbook.getWorksheet('Quotation');
  if (!worksheet) throw new Error('Quotation worksheet missing');
  const snapshot = captureTemplateDrawings({
    workbook,
    worksheet,
    headerRow: 7,
    itemStartRow: 8,
    footerStartRow: 12,
    imageColumn: 2,
  });
  const dimensions = [
    { width: 1000, height: 1000 },
    { width: 3000, height: 4000 },
  ];
  const mediaSha256 = createHash('sha256').update(PNG).digest('hex');
  const productImages: OoxmlExpectedProductImage[] = dimensions.map(({ width, height }, index) => {
    const rowNumber = 8 + index;
    const cell = measureQuotationImageCell(worksheet, rowNumber, 2);
    const fit = fitImageIntoCell({
      sourceWidth: width,
      sourceHeight: height,
      cellWidthPx: cell.widthPx,
      cellHeightPx: cell.heightPx,
      paddingPx: 4,
    });
    const anchor: QuotationProductImageAnchor = {
      productId: `product-${index + 1}`,
      rowNumber,
      columnNumber: 2,
      nativeCol: 1,
      nativeRow: rowNumber - 1,
      nativeColOff: pixelsToEmu(fit.offsetX),
      nativeRowOff: pixelsToEmu(fit.offsetY),
      widthPx: cell.widthPx,
      heightPx: cell.heightPx,
      fit,
      mediaSha256,
    };
    return { anchor, fit };
  });
  return {
    snapshot,
    options: {
      sheetName: 'Quotation',
      fixedImages: snapshot.fixedImages,
      productImages,
    },
  };
}

async function generatedWorkbook(): Promise<Buffer> {
  return buildQuotationWorkbookFromTemplate({
    templateBuffer: TEMPLATE,
    sheetName: 'Quotation',
    headerRow: 7,
    itemStartRow: 8,
    fieldMapping: FIELD_MAPPING,
    header: {
      companyName: 'Example Ltd.',
      contactPerson: 'Jerry',
      email: 'sales@example.com',
      phone: '+86 190 7428 9250',
      quotationTitle: 'October Price List',
    },
    currencyCode: 'USD',
    markupPercent: '15',
    exchangeRate: '0.1385',
    products: [product('product-1', 1000, 1000), product('product-2', 3000, 4000)],
    generatedAt: new Date('2026-10-30T10:30:00.000Z'),
  });
}

async function rewritePackage(
  buffer: Buffer,
  update: (zip: JSZip) => Promise<void> | void,
): Promise<Buffer> {
  const zip = await JSZip.loadAsync(buffer);
  await update(zip);
  return zip.generateAsync({ type: 'nodebuffer' });
}

async function drawingPart(zip: JSZip): Promise<{ path: string; xml: string }> {
  const path = Object.keys(zip.files).find((name) => /^xl\/drawings\/drawing\d+\.xml$/.test(name));
  if (!path) throw new Error('Drawing part missing');
  return { path, xml: await zip.file(path)!.async('string') };
}

describe('quotation OOXML image package', () => {
  it('validates local relationships and product anchors generated by the ExcelJS path', async () => {
    const buffer = await generatedWorkbook();
    const { options } = await expectedPackage();
    const report = await validateQuotationOoxmlImages(buffer, options);

    expect(report).toMatchObject({
      valid: true,
      repaired: false,
      productAnchors: 2,
      errors: [],
    });
  });

  it('repairs only product anchor coordinates that still point to the expected media', async () => {
    const buffer = await generatedWorkbook();
    const { options } = await expectedPackage();
    const corrupted = await rewritePackage(buffer, async (zip) => {
      const drawing = await drawingPart(zip);
      const start = drawing.xml.indexOf('<xdr:oneCellAnchor');
      expect(start).toBeGreaterThanOrEqual(0);
      const before = drawing.xml.slice(0, start);
      const after = drawing.xml.slice(start);
      const changed = after
        .replace(/(<xdr:row>)(\d+)(<\/xdr:row>)/, '$10$3')
        .replace(/(<xdr:ext\b[^>]*\bcx=")\d+("[^>]*\bcy=")\d+/, '$11$21');
      zip.file(drawing.path, `${before}${changed}`);
    });

    const initial = await validateQuotationOoxmlImages(corrupted, options);
    expect(initial.valid).toBe(false);
    expect(initial.errors).toContainEqual(
      expect.objectContaining({
        code: 'OOXML_PRODUCT_ANCHOR_MISMATCH',
        repairable: true,
      }),
    );

    const repaired = await ensureQuotationOoxmlImages(corrupted, options);
    expect(repaired.report).toMatchObject({ valid: true, repaired: true });
    await expect(validateQuotationOoxmlImages(repaired.buffer, options)).resolves.toMatchObject({
      valid: true,
      repaired: false,
    });
  });

  it('rejects a package whose product image media part is missing', async () => {
    const buffer = await generatedWorkbook();
    const { options } = await expectedPackage();
    const missingMedia = await rewritePackage(buffer, (zip) => {
      const media = Object.keys(zip.files)
        .filter((name) => /^xl\/media\//.test(name) && !zip.files[name]?.dir)
        .sort();
      const productMedia = media.at(-1);
      if (!productMedia) throw new Error('Product media missing');
      zip.remove(productMedia);
    });

    await expect(validateQuotationOoxmlImages(missingMedia, options)).rejects.toMatchObject({
      reason: 'OOXML_MEDIA_MISSING',
    });
  });

  it('rejects IMAGE and DISPIMG worksheet formulas instead of publishing a linked image', async () => {
    const buffer = await generatedWorkbook();
    const { options } = await expectedPackage();
    const formulaPackage = await rewritePackage(buffer, async (zip) => {
      const sheetPath = 'xl/worksheets/sheet1.xml';
      const sheet = zip.file(sheetPath);
      if (!sheet) throw new Error('Worksheet part missing');
      const xml = await sheet.async('string');
      zip.file(
        sheetPath,
        xml.replace('</worksheet>', '<extLst><f>DISPIMG("id",1)</f></extLst></worksheet>'),
      );
    });

    const report = await validateQuotationOoxmlImages(formulaPackage, options);
    expect(report.valid).toBe(false);
    expect(report.errors).toContainEqual(
      expect.objectContaining({
        code: 'OOXML_IMAGE_FORMULA_FORBIDDEN',
        repairable: false,
      }),
    );
    await expect(ensureQuotationOoxmlImages(formulaPackage, options)).rejects.toMatchObject({
      reason: 'OOXML_VALIDATION_FAILED',
    });
  });
});
