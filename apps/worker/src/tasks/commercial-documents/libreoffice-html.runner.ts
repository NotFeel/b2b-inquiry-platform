import { spawn } from 'node:child_process';
import { constants as fsConstants, promises as fs } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';

export interface HtmlConversionInput {
  executable: string;
  inputPath: string;
  outputDir: string;
  profileDir: string;
  timeoutMs: number;
}

export interface HtmlConversionResult {
  outputPath: string;
  durationMs: number;
}

/**
 * Converts a fully self-contained HTML document to PDF with the same headless
 * LibreOffice image used by the Excel→PDF pipeline. The HTML is generated by
 * our own renderer: no scripts, no external URLs and no file:// references.
 */
export async function convertHtmlWithLibreOffice(
  input: HtmlConversionInput,
): Promise<HtmlConversionResult> {
  try {
    await fs.access(input.executable, fsConstants.X_OK);
  } catch {
    throw new Error('COMMERCIAL_DOCUMENT_CONVERTER_UNAVAILABLE');
  }

  const startedAt = Date.now();
  const expectedOutput = join(input.outputDir, `${basename(input.inputPath, '.html')}.pdf`);
  const binaryDir = dirname(input.executable);
  const args = [
    `-env:UserInstallation=${pathToFileURL(input.profileDir).href}`,
    '--headless',
    '--nologo',
    '--nodefault',
    '--nofirststartwizard',
    '--convert-to',
    'pdf:writer_web_pdf_Export',
    '--outdir',
    input.outputDir,
    input.inputPath,
  ];

  await new Promise<void>((resolve, reject) => {
    const child = spawn(input.executable, args, {
      cwd: input.outputDir,
      shell: false,
      detached: process.platform !== 'win32',
      stdio: ['ignore', 'ignore', 'pipe'],
      env: {
        HOME: input.profileDir,
        TMPDIR: input.outputDir,
        LANG: 'C.UTF-8',
        LC_ALL: 'C.UTF-8',
        PATH: `${binaryDir}:/usr/local/bin:/usr/bin:/bin`,
        SAL_USE_VCLPLUGIN: 'svp',
      },
    });

    let stderrBytes = 0;
    child.stderr?.on('data', (chunk: Buffer) => {
      stderrBytes += chunk.byteLength;
      if (stderrBytes > 16 * 1024) child.stderr?.destroy();
    });

    let settled = false;
    const finish = (error?: Error) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (error) reject(error);
      else resolve();
    };
    const killTree = () => {
      if (!child.pid) return;
      try {
        if (process.platform === 'win32') child.kill('SIGKILL');
        else process.kill(-child.pid, 'SIGKILL');
      } catch {
        child.kill('SIGKILL');
      }
    };
    const timer = setTimeout(() => {
      killTree();
      finish(new Error('COMMERCIAL_DOCUMENT_CONVERSION_TIMEOUT'));
    }, input.timeoutMs);
    timer.unref?.();

    child.once('error', (error: NodeJS.ErrnoException) => {
      finish(
        new Error(
          error.code === 'ENOENT'
            ? 'COMMERCIAL_DOCUMENT_CONVERTER_UNAVAILABLE'
            : 'COMMERCIAL_DOCUMENT_CONVERSION_FAILED',
        ),
      );
    });
    child.once('close', (code, signal) => {
      if (settled) return;
      if (code !== 0) {
        finish(
          new Error(
            `COMMERCIAL_DOCUMENT_CONVERSION_FAILED_${signal ?? code ?? 'unknown'}`,
          ),
        );
        return;
      }
      finish();
    });
  });

  try {
    const stat = await fs.stat(expectedOutput);
    if (!stat.isFile() || stat.size === 0) throw new Error('not_a_file');
  } catch {
    throw new Error('COMMERCIAL_DOCUMENT_OUTPUT_INVALID');
  }
  return { outputPath: expectedOutput, durationMs: Date.now() - startedAt };
}
