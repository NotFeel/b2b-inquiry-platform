import { spawn } from 'node:child_process';
import { promises as fs } from 'node:fs';
import { basename, delimiter, dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { resolveExecutablePath } from '../resolve-executable';

export interface HtmlConversionInput {
  executable: string;
  inputPath: string;
  outputDir: string;
  profileDir: string;
  timeoutMs: number;
}

export interface HtmlConversionResult {
  outputPath: string;
  durationMs: number;
}

export class HtmlConversionError extends Error {
  constructor(
    message: string,
    readonly exitCode: number | null = null,
    readonly signal: NodeJS.Signals | null = null,
    readonly stderr = '',
  ) {
    super(message);
    this.name = 'HtmlConversionError';
  }
}

/**
 * Converts a fully self-contained HTML document to PDF with the same headless
 * LibreOffice image used by the Excel→PDF pipeline. The HTML is generated by
 * our own renderer: no scripts, no external URLs and no file:// references.
 */
export async function convertHtmlWithLibreOffice(
  input: HtmlConversionInput,
): Promise<HtmlConversionResult> {
  const executable = await resolveExecutablePath(input.executable);
  if (!executable) {
    throw new Error('COMMERCIAL_DOCUMENT_CONVERTER_UNAVAILABLE');
  }

  const startedAt = Date.now();
  // The child runs with `cwd` set to its private output directory. Convert all
  // workspace paths first; a relative WORKER_TMP_DIR otherwise makes
  // LibreOffice resolve the source HTML against that nested output directory
  // and exit with "source file could not be loaded".
  const inputPath = resolve(input.inputPath);
  const outputDir = resolve(input.outputDir);
  const profileDir = resolve(input.profileDir);
  const expectedOutput = join(outputDir, `${basename(inputPath, '.html')}.pdf`);
  const binaryDir = dirname(executable);
  const args = [
    `-env:UserInstallation=${pathToFileURL(profileDir).href}`,
    '--headless',
    '--nologo',
    '--nodefault',
    '--nofirststartwizard',
    '--convert-to',
    'pdf:writer_web_pdf_Export',
    '--outdir',
    outputDir,
    inputPath,
  ];

  await new Promise<void>((resolve, reject) => {
    const child = spawn(executable, args, {
      cwd: outputDir,
      shell: false,
      detached: process.platform !== 'win32',
      stdio: ['ignore', 'ignore', 'pipe'],
      env: {
        HOME: profileDir,
        TMPDIR: outputDir,
        LANG: 'C.UTF-8',
        LC_ALL: 'C.UTF-8',
        PATH: [binaryDir, process.env.PATH, '/usr/local/bin', '/usr/bin', '/bin']
          .filter((entry): entry is string => Boolean(entry))
          .join(delimiter),
        SAL_USE_VCLPLUGIN: 'svp',
      },
    });

    let stderrBytes = 0;
    let stderrText = '';
    child.stderr?.on('data', (chunk: Buffer) => {
      stderrBytes += chunk.byteLength;
      if (stderrText.length < 4_096) {
        stderrText += chunk.toString('utf8').slice(0, 4_096 - stderrText.length);
      }
      if (stderrBytes > 16 * 1024) child.stderr?.destroy();
    });

    let settled = false;
    const finish = (error?: Error) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (error) reject(error);
      else resolve();
    };
    const killTree = () => {
      if (!child.pid) return;
      try {
        if (process.platform === 'win32') child.kill('SIGKILL');
        else process.kill(-child.pid, 'SIGKILL');
      } catch {
        child.kill('SIGKILL');
      }
    };
    const timer = setTimeout(() => {
      killTree();
      finish(new Error('COMMERCIAL_DOCUMENT_CONVERSION_TIMEOUT'));
    }, input.timeoutMs);
    timer.unref?.();

    child.once('error', (error: NodeJS.ErrnoException) => {
      finish(
        new HtmlConversionError(
          error.code === 'ENOENT'
            ? 'COMMERCIAL_DOCUMENT_CONVERTER_UNAVAILABLE'
            : 'COMMERCIAL_DOCUMENT_CONVERSION_FAILED',
        ),
      );
    });
    child.once('close', (code, signal) => {
      if (settled) return;
      if (code !== 0) {
        finish(
          new HtmlConversionError(
            'COMMERCIAL_DOCUMENT_CONVERSION_FAILED',
            code,
            signal,
            stderrText.trim(),
          ),
        );
        return;
      }
      finish();
    });
  });

  try {
    const stat = await fs.stat(expectedOutput);
    if (!stat.isFile() || stat.size === 0) throw new Error('not_a_file');
  } catch {
    throw new Error('COMMERCIAL_DOCUMENT_OUTPUT_INVALID');
  }
  return { outputPath: expectedOutput, durationMs: Date.now() - startedAt };
}
